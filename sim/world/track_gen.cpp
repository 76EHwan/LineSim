#include "world/track_gen.h"

#include <cmath>
#include <cstdio>
#include <random>
#include <sstream>
#include <vector>

#include "world/track.h"

namespace {
constexpr double kPi = 3.14159265358979323846;
constexpr double kR = 0.25;

struct Piece {
	bool arc;
	double len;    // straight length
	int deg;       // arc angle, + = left
};

// Pose at the end of the pieces, starting at the origin heading +x.
void walk(const std::vector<Piece>& ps, double* x, double* y, double* th) {
	*x = *y = *th = 0;
	for (const Piece& p : ps) {
		if (!p.arc) {
			*x += p.len * std::cos(*th);
			*y += p.len * std::sin(*th);
		} else {
			int turn = p.deg > 0 ? 1 : -1;
			double phi = p.deg * kPi / 180.0;
			double cx = *x - turn * kR * std::sin(*th), cy = *y + turn * kR * std::cos(*th);
			double rx = *x - cx, ry = *y - cy;
			*x = cx + rx * std::cos(phi) - ry * std::sin(phi);
			*y = cy + rx * std::sin(phi) + ry * std::cos(phi);
			*th += phi;
		}
	}
}

double round_to(double v, double q) { return std::round(v / q) * q; }

std::string to_json(const std::vector<Piece>& ps, unsigned seed, double goal_s, double start_s) {
	std::ostringstream o;
	o.precision(6);
	o << "// Random ZETIN-rule course generated by LineSim (seed " << seed << ").\n"
	  << "{\n  \"name\": \"random_" << seed << "\",\n  \"closed\": true,\n  \"line_width\": 0.02,\n"
	  << "  \"goal_s\": " << goal_s << ",\n  \"start_s\": " << start_s << ",\n  \"auto_turn_marks\": true,\n"
	  << "  \"segments\": [\n";
	for (size_t i = 0; i < ps.size(); i++) {
		if (ps[i].arc)
			o << "    { \"arc\": " << ps[i].deg << " }";
		else
			o << "    { \"straight\": " << std::round(ps[i].len * 10000) / 10000 << " }";
		o << (i + 1 < ps.size() ? ",\n" : "\n");
	}
	o << "  ]\n}\n";
	return o.str();
}
}  // namespace

std::string generate_track(const TrackGenOptions& opt, std::string* err, int* attempts_out) {
	std::mt19937 rng(opt.seed);
	auto uni = [&](double a, double b) { return std::uniform_real_distribution<double>(a, b)(rng); };
	auto pick = [&](int n) { return std::uniform_int_distribution<int>(0, n - 1)(rng); };
	const int angle_w[6] = {3, 4, 2, 3, 1, 1};   // 45 90 135 180 225 270
	auto rand_angle = [&]() {
		int tot = 0;
		for (int w : angle_w)
			tot += w;
		int r = pick(tot);
		for (int k = 0; k < 6; k++) {
			if (r < angle_w[k])
				return 45 * (k + 1);
			r -= angle_w[k];
		}
		return 90;
	};

	// end-mark straight first: goal 0.2 m in, start 0.45 m after the goal, 0.35 m after the start
	const double start_len = 1.0, goal_s = 0.2, start_s = 0.65;

	for (int attempt = 1; attempt <= 200000; attempt++) {
		std::vector<Piece> ps;
		ps.push_back({false, start_len, 0});
		int n = opt.min_pieces + pick(opt.max_pieces - opt.min_pieces + 1);
		int turn_sum = 0;
		for (int i = 0; i < n; i++) {
			const Piece& prev = ps.back();
			bool arc = prev.arc ? uni(0, 1) < 0.35 : true;
			if (!arc) {
				ps.push_back({false, round_to(uni(0.15, 1.0), 0.05), 0});
			} else {
				int a = rand_angle();
				int sign = uni(0, 1) < 0.5 ? 1 : -1;
				if (prev.arc)
					sign = prev.deg > 0 ? -1 : 1;   // same-direction arcs would just be one arc
				ps.push_back({true, 0, sign * a});
				turn_sum += sign * a;
			}
		}
		// close the turning: +-360 (simple loop) or 0 (figure eight: needs a crossing)
		const bool want_cross = opt.crossings > 0 || (opt.crossings < 0 && opt.min_crossings > 0);
		int targets[3] = {360, -360, 0};
		int target = targets[0];
		int best = 1 << 30;
		for (int t : targets) {
			if (t == 0 && opt.crossings == 0)
				continue;
			if (std::abs(t - turn_sum) < best) {
				best = std::abs(t - turn_sum);
				target = t;
			}
		}
		// a closed course with zero total turning (figure eight) always crosses itself
		if (want_cross && uni(0, 1) < 0.75)
			target = 0;
		int rem = target - turn_sum;
		while (rem != 0) {
			int a = std::min(std::abs(rem), 270);
			int sign = rem > 0 ? 1 : -1;
			if (ps.back().arc && (ps.back().deg > 0) == (sign > 0))
				ps.push_back({false, round_to(uni(0.2, 0.6), 0.05), 0});
			ps.push_back({true, 0, sign * a});
			rem -= sign * a;
		}
		ps.push_back({false, 0.3, 0});   // into the end-mark straight (merged with it)

		// close the position: lengthen/shorten two non-parallel straights
		double ex, ey, eth;
		walk(ps, &ex, &ey, &eth);
		std::vector<int> si;
		std::vector<double> sth;
		{
			double th = 0;
			for (size_t i = 0; i < ps.size(); i++) {
				if (ps[i].arc)
					th += ps[i].deg * kPi / 180.0;
				else if (i > 0) {   // never touch the end-mark straight
					si.push_back(static_cast<int>(i));
					sth.push_back(th);
				}
			}
		}
		bool closed = false;
		double best_cost = 1e9;
		std::vector<Piece> best_ps;
		for (size_t a = 0; a < si.size(); a++)
			for (size_t b = a + 1; b < si.size(); b++) {
				double ux = std::cos(sth[a]), uy = std::sin(sth[a]);
				double vx = std::cos(sth[b]), vy = std::sin(sth[b]);
				double det = ux * vy - uy * vx;
				if (std::fabs(det) < 0.6)
					continue;
				// da*u + db*v = -(ex, ey)
				double da = (-ex * vy + ey * vx) / det;
				double db = (-ey * ux + ex * uy) / det;
				double la = ps[si[a]].len + da, lb = ps[si[b]].len + db;
				if (la < 0.15 || lb < 0.15 || la > 2.5 || lb > 2.5)
					continue;
				double cost = std::fabs(da) + std::fabs(db);
				if (cost < best_cost) {
					best_cost = cost;
					best_ps = ps;
					best_ps[si[a]].len = la;
					best_ps[si[b]].len = lb;
					closed = true;
				}
			}
		if (!closed)
			continue;

		std::string text = to_json(best_ps, opt.seed, goal_s, start_s);
		Track t;
		std::string e;
		if (!t.load_text(text, "random", &e))
			continue;
		if (t.length() < opt.min_length || t.length() > opt.max_length)
			continue;
		const int nc = static_cast<int>(t.crossings().size());
		if (opt.crossings >= 0 ? nc != opt.crossings : nc < opt.min_crossings)
			continue;
		if (!t.rule_problems(opt.board_w - 0.2, opt.board_h - 0.2).empty())
			continue;
		if (attempts_out)
			*attempts_out = attempt;
		return text;
	}
	*err = "no valid course found (try other options)";
	return "";
}
