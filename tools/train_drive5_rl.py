"""Train standalone Drive 5 RL policy via parallel OpenAI-ES rollouts (supports --endless background mode)."""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
import json
import os
from pathlib import Path
import shutil
import signal
import subprocess
import tempfile
import time

import numpy as np

OBS_DIM = 10
HID_DIM = 16
ACT_DIM = 2
PARAM_COUNT = OBS_DIM * HID_DIM + HID_DIM + HID_DIM * ACT_DIM + ACT_DIM

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SIM = REPO_ROOT / "build" / "Release" / "linesim.exe"
DEFAULT_TRACK = REPO_ROOT / "tracks" / "finals_1_5x_championship.json"
DEFAULT_ROBOT = REPO_ROOT / "robots" / "full.json"
DEFAULT_STATE_DIR = REPO_ROOT / "runs" / "drive5_rl"
WEIGHTS_HEADER = REPO_ROOT / "firmware" / "Main" / "Inc" / "fifth_rl_weights.h"


def evaluate_weights(
    weights: np.ndarray,
    sim_exe: Path,
    track: Path,
    robot: Path,
    work_dir: Path,
    tag: str,
) -> tuple[float, dict]:
    """Run Drive 1+5 in LineSim with candidate weights and return (reward, metrics)."""
    run_dir = work_dir / f"eval_{tag}"
    run_dir.mkdir(parents=True, exist_ok=True)
    w_file = run_dir / "weights.txt"
    w_file.write_text("\n".join(f"{float(v):.8f}" for v in weights) + "\n", encoding="utf-8")

    env = os.environ.copy()
    env["LINESIM_FIFTH_WEIGHTS"] = str(w_file)

    cmd = [
        str(sim_exe),
        "run",
        "--track",
        str(track),
        "--robot",
        str(robot),
        "--drives",
        "1,5",
        "--quiet",
        "--max-time",
        "70",
        "--out",
        str(run_dir),
    ]
    try:
        proc = subprocess.run(cmd, env=env, cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=65)
    except subprocess.TimeoutExpired:
        shutil.rmtree(run_dir, ignore_errors=True)
        return -200.0, {"ok": False, "reason": "timeout"}

    summary_path = run_dir / "summary.json"
    if proc.returncode != 0 or not summary_path.exists():
        shutil.rmtree(run_dir, ignore_errors=True)
        return -200.0, {"ok": False, "reason": f"rc={proc.returncode}"}

    try:
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
    except Exception:
        shutil.rmtree(run_dir, ignore_errors=True)
        return -200.0, {"ok": False, "reason": "bad_json"}

    d5 = None
    for d in summary.get("drives", []):
        if d.get("drive") == 5:
            d5 = d
            break

    shutil.rmtree(run_dir, ignore_errors=True)
    if d5 is None:
        return -200.0, {"ok": False, "reason": "no_drive5"}

    outcome = str(d5.get("outcome", ""))
    marker_ok = d5.get("marker_check") == "OK"
    max_lat = float(d5.get("max_lat_mm", 999.0))
    dist_m = float(d5.get("distance_m", 0.0))
    lap_s = float(d5.get("lap_time_fw", -1.0))
    max_beta = float(d5.get("max_beta_deg", 0.0))
    track_len = float(summary.get("track_length_m", 75.0))

    finished_ok = outcome.startswith("finished") and marker_ok and max_lat <= 295.0 and lap_s > 0.0
    if not finished_ok:
        prog = min(dist_m / max(track_len, 1.0), 1.0)
        reward = -100.0 + 40.0 * prog - (0.2 * max(0.0, max_lat - 295.0))
        if not marker_ok:
            reward -= 15.0
        return reward, {
            "ok": False,
            "outcome": outcome,
            "marker_check": d5.get("marker_check"),
            "lap_s": lap_s,
            "dist_m": dist_m,
            "max_lat_mm": max_lat,
            "max_beta_deg": max_beta,
        }

    beta_pen = 0.02 * max(0.0, max_beta - 28.0)
    reward = -lap_s - beta_pen
    return reward, {
        "ok": True,
        "outcome": outcome,
        "lap_s": lap_s,
        "dist_m": dist_m,
        "max_lat_mm": max_lat,
        "rms_lat_mm": float(d5.get("rms_lat_mm", 0.0)),
        "max_beta_deg": max_beta,
    }


def centered_ranks(x: np.ndarray) -> np.ndarray:
    ranks = np.empty(len(x), dtype=np.float64)
    ranks[np.argsort(x)] = np.arange(len(x), dtype=np.float64)
    return ranks / (len(x) - 1.0) - 0.5


def write_weights_header(weights: np.ndarray, header_path: Path) -> None:
    vals = ",\n".join(
        "\t" + ", ".join(f"{float(v):+.7f}f" for v in weights[i : i + 8])
        for i in range(0, len(weights), 8)
    )
    content = f"""#ifndef FIFTH_RL_WEIGHTS_H
#define FIFTH_RL_WEIGHTS_H

#define FIFTH_RL_OBS_DIM {OBS_DIM}
#define FIFTH_RL_HID_DIM {HID_DIM}
#define FIFTH_RL_ACT_DIM {ACT_DIM}
#define FIFTH_RL_PARAM_COUNT (FIFTH_RL_OBS_DIM * FIFTH_RL_HID_DIM + FIFTH_RL_HID_DIM + FIFTH_RL_HID_DIM * FIFTH_RL_ACT_DIM + FIFTH_RL_ACT_DIM)

/* Trained standalone Drive 5 RL policy weights (generated by tools/train_drive5_rl.py) */
static const float g_fifth_rl_default_weights[FIFTH_RL_PARAM_COUNT] = {{
{vals}
}};

#endif /* FIFTH_RL_WEIGHTS_H */
"""
    header_path.write_text(content, encoding="utf-8")


def save_checkpoint(
    state_dir: Path,
    gen: int,
    theta: np.ndarray,
    m: np.ndarray,
    v: np.ndarray,
    best_theta: np.ndarray,
    best_r: float,
    best_m: dict,
) -> None:
    state_dir.mkdir(parents=True, exist_ok=True)
    (state_dir / "best_weights.txt").write_text(
        "\n".join(f"{float(x):.8f}" for x in best_theta) + "\n", encoding="utf-8"
    )
    payload = {
        "gen": gen,
        "best_r": best_r,
        "best_m": best_m,
        "theta": theta.tolist(),
        "m": m.tolist(),
        "v": v.tolist(),
        "best_theta": best_theta.tolist(),
    }
    tmp = state_dir / "state.json.tmp"
    tmp.write_text(json.dumps(payload), encoding="utf-8")
    tmp.replace(state_dir / "state.json")


def main() -> int:
    ap = argparse.ArgumentParser(description="Train standalone Drive 5 RL policy with OpenAI-ES")
    ap.add_argument("--sim", type=Path, default=DEFAULT_SIM)
    ap.add_argument("--track", type=Path, default=DEFAULT_TRACK)
    ap.add_argument("--robot", type=Path, default=DEFAULT_ROBOT)
    ap.add_argument("--state-dir", type=Path, default=DEFAULT_STATE_DIR)
    ap.add_argument("--gens", type=int, default=15, help="Max generations (ignored when --endless)")
    ap.add_argument("--endless", action="store_true", help="Run continuously in background until Ctrl+C")
    ap.add_argument("--fresh", action="store_true", help="Ignore existing checkpoint and start from zero")
    ap.add_argument("--pairs", type=int, default=8, help="Antithetic pairs per gen (2*pairs rollouts)")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--sigma", type=float, default=0.08)
    ap.add_argument("--lr", type=float, default=0.03)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    stop_requested = False

    def handle_sig(signum, frame):
        nonlocal stop_requested
        stop_requested = True
        print("\n[signal] Stopping cleanly after current generation...", flush=True)

    signal.signal(signal.SIGINT, handle_sig)
    if hasattr(signal, "SIGTERM"):
        signal.signal(signal.SIGTERM, handle_sig)

    rng = np.random.default_rng(args.seed)
    theta = np.zeros(PARAM_COUNT, dtype=np.float64)
    m = np.zeros(PARAM_COUNT, dtype=np.float64)
    v = np.zeros(PARAM_COUNT, dtype=np.float64)
    best_theta = theta.copy()
    best_r = -1e9
    best_m: dict = {}
    start_gen = 0
    beta1, beta2, eps_adam = 0.9, 0.999, 1e-8

    state_file = args.state_dir / "state.json"
    if not args.fresh and state_file.exists():
        try:
            saved = json.loads(state_file.read_text(encoding="utf-8"))
            theta = np.array(saved["theta"], dtype=np.float64)
            m = np.array(saved["m"], dtype=np.float64)
            v = np.array(saved["v"], dtype=np.float64)
            best_theta = np.array(saved["best_theta"], dtype=np.float64)
            best_r = float(saved["best_r"])
            best_m = dict(saved["best_m"])
            start_gen = int(saved["gen"])
            print(
                f"[resume] gen={start_gen} best_lap={best_m.get('lap_s', -1):.2f}s (r={best_r:.3f})",
                flush=True,
            )
        except Exception as exc:
            print(f"[warn] Failed to resume checkpoint ({exc}), starting fresh", flush=True)

    work_dir = args.state_dir / "_tmp"
    shutil.rmtree(work_dir, ignore_errors=True)
    work_dir.mkdir(parents=True, exist_ok=True)
    try:
        if start_gen == 0:
            base_r, base_m = evaluate_weights(theta, args.sim, args.track, args.robot, work_dir, "base")
            print(f"[baseline] reward={base_r:.3f} {base_m}", flush=True)
            best_r = base_r
            best_m = base_m
            best_theta = theta.copy()
            save_checkpoint(args.state_dir, 0, theta, m, v, best_theta, best_r, best_m)

        gen = start_gen
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            while not stop_requested and (args.endless or gen < start_gen + args.gens):
                gen += 1
                t0 = time.time()
                eps = rng.standard_normal((args.pairs, PARAM_COUNT))
                cands = []
                for p in range(args.pairs):
                    cands.append((theta + args.sigma * eps[p], f"g{gen}_p{p}"))
                    cands.append((theta - args.sigma * eps[p], f"g{gen}_m{p}"))

                futs = [
                    pool.submit(evaluate_weights, w, args.sim, args.track, args.robot, work_dir, tag)
                    for w, tag in cands
                ]
                results = [f.result() for f in futs]
                rewards = np.array([r[0] for r in results], dtype=np.float64)

                new_best = False
                for idx, (r, met) in enumerate(results):
                    if met.get("ok") and (not best_m.get("ok") or r > best_r):
                        best_r = r
                        best_theta = cands[idx][0].copy()
                        best_m = met
                        new_best = True

                shaped = centered_ranks(rewards)
                grad = np.zeros(PARAM_COUNT, dtype=np.float64)
                for p in range(args.pairs):
                    grad += (shaped[2 * p] - shaped[2 * p + 1]) * eps[p]
                grad /= 2.0 * args.pairs * args.sigma

                m = beta1 * m + (1.0 - beta1) * grad
                v = beta2 * v + (1.0 - beta2) * (grad * grad)
                m_hat = m / (1.0 - beta1**gen)
                v_hat = v / (1.0 - beta2**gen)
                theta = np.clip(theta + args.lr * m_hat / (np.sqrt(v_hat) + eps_adam), -1.5, 1.5)

                mean_r, mean_m = evaluate_weights(theta, args.sim, args.track, args.robot, work_dir, f"g{gen}_mean")
                if mean_m.get("ok") and (not best_m.get("ok") or mean_r > best_r):
                    best_r = mean_r
                    best_theta = theta.copy()
                    best_m = mean_m
                    new_best = True

                save_checkpoint(args.state_dir, gen, theta, m, v, best_theta, best_r, best_m)
                if new_best:
                    write_weights_header(best_theta, WEIGHTS_HEADER)

                ok_cnt = sum(1 for _, met in results if met.get("ok"))
                dt = time.time() - t0
                tag_b = " *NEW BEST*" if new_best else ""
                print(
                    f"[gen {gen:03d}] dt={dt:.1f}s ok={ok_cnt}/{len(results)} "
                    f"mean_r={rewards.mean():.3f} theta_lap={mean_m.get('lap_s', -1):.2f}s "
                    f"best_lap={best_m.get('lap_s', -1):.2f}s (lat={best_m.get('max_lat_mm', -1):.1f}mm){tag_b}",
                    flush=True,
                )

        if best_m.get("ok"):
            write_weights_header(best_theta, WEIGHTS_HEADER)
        print(f"[saved] checkpoint={state_file} header={WEIGHTS_HEADER}", flush=True)
    finally:
        shutil.rmtree(work_dir, ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
